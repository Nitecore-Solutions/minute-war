<#
  Opens two Cloudflare quick tunnels (:3000 API, :3002 WS) and rewrites
  mobile/.env with the resulting URLs, so a phone on mobile data can reach a
  dev build on this PC.

    .\tools\start-tunnels.ps1

  Quick tunnel URLs are random and change every restart, which is exactly why
  this script exists: never hand-edit mobile/.env when tunnels are in use.

  Requires the backend already running:
    cd backend
    npm run dev      (API :3000)
    npm run dev:ws   (WS  :3002)
#>

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$exe = Join-Path $PSScriptRoot "cloudflared.exe"
$logs = Join-Path $root ".logs"

if (-not (Test-Path $exe)) {
    throw "cloudflared.exe not found at $exe"
}

New-Item -ItemType Directory -Force -Path $logs | Out-Null

function Test-Port([int]$port) {
    try {
        $null = Invoke-WebRequest "http://localhost:$port/api/health" -UseBasicParsing -TimeoutSec 4
        return $true
    } catch {
        # :3002 is the raw ws server, so /api/health is expected to 404 there.
        # Any HTTP response at all means something is listening.
        try {
            $null = Invoke-WebRequest "http://localhost:$port/" -UseBasicParsing -TimeoutSec 4
            return $true
        } catch {
            if ($_.Exception.Response) { return $true }
            return $false
        }
    }
}

if (-not (Test-Port 3000)) {
    Write-Warning "Nothing is listening on :3000. Start it with: cd backend; npm run dev"
}
if (-not (Test-Port 3002)) {
    Write-Warning "Nothing is listening on :3002. Start it with: cd backend; npm run dev:ws"
}

# Kill any tunnel this script started previously.
Get-CimInstance Win32_Process -Filter "Name='cloudflared.exe'" |
    Where-Object { $_.CommandLine -match 'tunnel\s+--url' } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
Start-Sleep -Seconds 2

function Start-Tunnel([int]$port, [string]$label) {
    Write-Host "  tunnel for :$port"
    return Start-Process -FilePath $exe `
        -ArgumentList "tunnel", "--url", "http://localhost:$port", "--no-autoupdate" `
        -RedirectStandardOutput (Join-Path $logs "$label.out.log") `
        -RedirectStandardError  (Join-Path $logs "$label.err.log") `
        -PassThru -WindowStyle Hidden
}

function Wait-Url($tunnel, [int]$seconds = 60) {
    # cloudflared writes ALL of its logging, including the line carrying the
    # URL, to STDERR. Its stdout log stays empty. Read both or this times out.
    $err = Join-Path $logs "tunnel.err.log"
    $out = Join-Path $logs "tunnel.out.log"

    $deadline = (Get-Date).AddSeconds($seconds)
    while ((Get-Date) -lt $deadline) {
        foreach ($file in @($err, $out)) {
            if (Test-Path $file) {
                $m = Select-String -Path $file -Pattern 'https://[a-z0-9-]+\.trycloudflare\.com' -AllMatches -ErrorAction SilentlyContinue
                if ($m) { return ($m.Matches | Select-Object -First 1).Value }
            }
        }
        Start-Sleep -Milliseconds 800
    }
    return $null
}

Write-Host "`nStarting tunnels..." -ForegroundColor Cyan

$apiTunnel  = Start-Tunnel 3000 "api"
$apiUrl = Wait-Url $apiTunnel
if (-not $apiUrl) { throw "the :3000 tunnel did not report a URL. See .logs\api.err.log" }

# Separate log files per tunnel, otherwise the second Wait-Url reads the first
# tunnel's URL and both sides end up pointing at the same place.
$wsTunnel = Start-Tunnel 3002 "ws"
$wsUrl = Wait-Url $wsTunnel
if (-not $wsUrl -or $wsUrl -eq $apiUrl) {
    throw "the :3002 tunnel did not report its own URL. See .logs\ws.err.log"
}

$body = @"
# Local development, going through two Cloudflare quick tunnels.
#
# AUTO-GENERATED by tools/start-tunnels.ps1 -- do not hand-edit.
# Run `npm run tunnels` from the repo root to refresh these.
#
# Prerequisites, each in its own terminal:
#   cd backend && npm run dev      Next.js API   :3000
#   cd backend && npm run dev:ws   WebSocket     :3002
#
# Then restart Expo with a cleared cache:
#   cd mobile && npx expo start --clear
#
#   API tunnel -> :3000
#   WS  tunnel -> :3002
EXPO_PUBLIC_API_URL=$apiUrl/api
EXPO_PUBLIC_WS_URL=$($wsUrl -replace '^https:', 'wss:')
"@

# Normalise to LF and strip any BOM. PowerShell 5.1 writes CRLF and
# -Encoding utf8 prepends a BOM; both are needless hazards in a dotenv file.
$body = ($body -replace "`r`n", "`n").TrimStart([char]0xFEFF)
$envPath = Join-Path $root "mobile\.env"
[System.IO.File]::WriteAllText($envPath, $body, (New-Object System.Text.UTF8Encoding $false))

Write-Host "`n  API  $apiUrl" -ForegroundColor Green
Write-Host "  WS   $wsUrl" -ForegroundColor Green
Write-Host "`n  mobile\.env updated." -ForegroundColor Green
Write-Host "  Now run:  cd mobile; npx expo start --clear`n" -ForegroundColor Yellow